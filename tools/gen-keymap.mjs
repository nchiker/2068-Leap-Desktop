"use strict";
// gen-keymap.mjs -- key map generator for Leap Desktop (docs/OBJECTS_EVENTS.md section 14.4).
//   node tools/gen-keymap.mjs <outDir> [keymap.txt]     CLI (default file src/kernel/keymap.txt)
// genKeymap(file, outDir) reads the key map text and writes <outDir>/keymap.inc: label KEYMAP, then 120 DB bytes
// (plain k = 0..39, then CS, then SS; KEYMAP + 40 plane + k).  Returns the written path.  Never hand-edit the output.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const KEY_ORDER = ['CS', 'Z', 'X', 'C', 'V', 'A', 'S', 'D', 'F', 'G', 'Q', 'W', 'E', 'R', 'T', '1', '2', '3', '4', '5',
  '0', '9', '8', '7', '6', 'P', 'O', 'I', 'U', 'Y', 'ENTER', 'L', 'K', 'J', 'H', 'SPACE', 'SS', 'M', 'N', 'B'];
export const NAMES = { ENTER: 13, LEFT: 8, RIGHT: 9, DOWN: 10, UP: 11, DELETE: 12, TAB: 14, BACKTAB: 15, MENU: 16, ESC: 27,
  BREAK: 3, CAPS: 1, SPACE: 32, HASH: 35, DASH: 45 };
const PLANES = ['plain', 'CS', 'SS'];

/** Parse keymap text; returns Uint8Array(120). `file` is only used in messages. */
export function parseKeymap(text, file = 'keymap.txt') {
  const rows = [];   // { ln, name, entries: [3 codes] }
  text.split(/\r?\n/).forEach((raw, i) => {
    const ln = i + 1;
    const err = msg => { throw new Error(`${file}:${ln}: ${msg}`); };
    const body = raw.replace(/(^|\s)#.*/, '').trim();   // a '#' starts a comment only at line start or after whitespace
    if (!body) return;
    const w = body.split(/\s+/);
    if (w.length !== 4) err(`expected a key name and 3 entries, got ${w.length} words: "${body}"`);
    const entries = w.slice(1).map((e, j) => {
      if (Object.hasOwn(NAMES, e)) return NAMES[e];
      if (e === '-') return 0;
      if (e.length === 1 && e.charCodeAt(0) >= 32 && e.charCodeAt(0) <= 126) return e.charCodeAt(0);
      return err(`bad ${PLANES[j]} entry "${e}" for key ${w[0]}`);
    });
    rows.push({ ln, name: w[0], entries });
  });
  const lastLn = text.split(/\r?\n/).length;
  if (rows.length !== 40) throw new Error(`${file}:${rows.length ? rows[rows.length - 1].ln : lastLn}: expected exactly 40 key lines, got ${rows.length}`);
  rows.forEach((r, k) => {
    if (r.name !== KEY_ORDER[k]) throw new Error(`${file}:${r.ln}: key ${k} should be ${KEY_ORDER[k]}, got ${r.name}`);
    if ((k === 0 || k === 36) && r.entries.some(c => c !== 0))
      throw new Error(`${file}:${r.ln}: key ${r.name} must have all entries '-'`);
  });
  const map = new Uint8Array(120);
  rows.forEach((r, k) => r.entries.forEach((c, p) => { map[40 * p + k] = c; }));
  const missing = [];
  for (let c = 32; c <= 126; c++) if (!map.includes(c)) missing.push(String.fromCharCode(c));
  if (missing.length) throw new Error(`${file}:${rows[rows.length - 1].ln}: printable ASCII missing from the map: ${missing.map(c => c === ' ' ? 'SPACE' : c).join(' ')}`);
  return map;
}

const show = c => c === 0 ? '-' : c < 32 ? `^${c}` : c === 127 ? 'DEL' : String.fromCharCode(c);

/** Read `file`, write <outDir>/keymap.inc; returns the written path. */
export function genKeymap(file, outDir) {
  const map = parseKeymap(readFileSync(file, 'utf8'), file);
  const lines = ['; keymap.inc -- GENERATED by tools/gen-keymap.mjs from keymap.txt (docs/OBJECTS_EVENTS.md 14.4); do not edit.',
    '; KEYMAP + 40 * plane + k, plane 0 plain, 1 CAPS SHIFT, 2 SYMBOL SHIFT; k = 5 * half-row + bit.', 'KEYMAP:'];
  for (let p = 0; p < 3; p++) {
    lines.push(`; ---- ${PLANES[p]}`);
    for (let k = 0; k < 40; k++) {
      const c = map[40 * p + k];
      lines.push(`        DB ${String(c).padStart(3)}              ; ${String(40 * p + k).padStart(3)}  ${PLANES[p]} k=${k} ${KEY_ORDER[k]}: ${show(c)}`);
    }
  }
  mkdirSync(outDir, { recursive: true });
  const path = join(outDir, 'keymap.inc');
  writeFileSync(path, lines.join('\n') + '\n');
  return path;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const [outDir, file] = [process.argv[2], process.argv[3] ?? join(root, 'src/kernel/keymap.txt')];
  if (!outDir) { console.error('usage: node tools/gen-keymap.mjs <outDir> [keymap.txt]'); process.exit(2); }
  console.log(genKeymap(file, outDir));
}
