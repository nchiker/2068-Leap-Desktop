"use strict";
// gen-tables.mjs -- generate src/gfx6/tables.inc (sjasmplus source: labels and data only) for the mode 6 graphics code.
// See docs/GRAPHICS_SPIKE.md sections 6 and 12.3. S1 tables: ROWTAB, LMASK, RMASK; later slices add more (one function each).
// Also src/gfx6/tables4.inc (page-aligned tables for chunk 4-5: LMASKP, RMASKP).
//   node tools/gen-tables.mjs       write src/gfx6/tables.inc and tables4.inc, print each path and size
//   import { genTables, genTables4 } from './gen-tables.mjs'   each returns the file text
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'gfx6', 'tables.inc');
const OUT4 = join(ROOT, 'src', 'gfx6', 'tables4.inc');

const hex4 = (v) => '$' + v.toString(16).toUpperCase().padStart(4, '0');
const hex2 = (v) => '$' + v.toString(16).toUpperCase().padStart(2, '0');

/** Address of pixel row y, byte column 0, in display file 1. */
export const rowAddr = (y) => 0x4000 + (y & 0xC0) * 32 + (y & 7) * 256 + (y & 0x38) * 4;

/** ROWTAB: 192 words, 8 per DW line. */
export function genRowtab() {
  const rows = Array.from({ length: 192 }, (_, y) => rowAddr(y));
  const bad = (m) => { throw new Error(`ROWTAB self-check failed: ${m}`); };
  if (new Set(rows).size !== 192) bad('values are not all distinct');
  for (const [y, a] of rows.entries()) {
    if (a < 0x4000 || a > 0x57E0) bad(`row ${y} = ${hex4(a)} out of range`);
    if (a & 0x1F) bad(`row ${y} = ${hex4(a)} has low 5 bits set`);
  }
  for (const [y, a] of [[0, 0x4000], [1, 0x4100], [8, 0x4020], [64, 0x4800], [191, 0x57E0]]) {
    if (rows[y] !== a) bad(`row ${y} = ${hex4(rows[y])}, expected ${hex4(a)}`);
  }
  const lines = ['ROWTAB:'];
  for (let y = 0; y < 192; y += 8) {
    lines.push(`\tDW ${rows.slice(y, y + 8).map(hex4).join(',')}\t; rows ${y}..${y + 7}`);
  }
  return lines.join('\n');
}

/** LMASK: $FF >> i (pixels i..7 of a byte). */
export function genLmask() {
  const v = Array.from({ length: 8 }, (_, i) => 0xFF >> i);
  return `LMASK:\n\tDB ${v.map(hex2).join(',')}`;
}

/** RMASK: ($FF << (7 - i)) AND $FF (pixels 0..i of a byte). */
export function genRmask() {
  const v = Array.from({ length: 8 }, (_, i) => (0xFF << (7 - i)) & 0xFF);
  return `RMASK:\n\tDB ${v.map(hex2).join(',')}`;
}

/** The full text of src/gfx6/tables.inc. */
export function genTables() {
  const head = '; src/gfx6/tables.inc -- GENERATED by tools/gen-tables.mjs. Do not edit by hand.\n' +
    '; Labels and data only: the including source places it (ROWTAB on a 512-byte boundary).\n';
  return [head, genRowtab(), genLmask(), genRmask()].join('\n') + '\n';
}

/** DB lines of 16 values for a 256-byte table. */
const dbLines = (v) => {
  const lines = [];
  for (let i = 0; i < 256; i += 16) lines.push(`\tDB ${v.slice(i, i + 16).map(hex2).join(',')}`);
  return lines.join('\n');
};

/** Check a 256-byte table: exact length and spot values. */
function check256(name, v, spots) {
  const bad = (m) => { throw new Error(`${name} self-check failed: ${m}`); };
  if (v.length !== 256) bad(`length ${v.length}, expected 256`);
  for (const [i, e] of spots) if (v[i] !== e) bad(`[${i}] = ${hex2(v[i])}, expected ${hex2(e)}`);
}

/** LMASKP: 256 bytes, [v] = $FF >> (v AND 7). */
export function genLmaskp() {
  const v = Array.from({ length: 256 }, (_, i) => 0xFF >> (i & 7));
  check256('LMASKP', v, [[0, 0xFF], [7, 0x01], [8, 0xFF], [13, 0x07], [255, 0x01]]);
  return `LMASKP:\n${dbLines(v)}`;
}

/** RMASKP: 256 bytes, [v] = ($FF << (7 - (v AND 7))) AND $FF. */
export function genRmaskp() {
  const v = Array.from({ length: 256 }, (_, i) => (0xFF << (7 - (i & 7))) & 0xFF);
  check256('RMASKP', v, [[0, 0x80], [7, 0xFF], [8, 0x80], [13, 0xFC], [255, 0xFF]]);
  return `RMASKP:\n${dbLines(v)}`;
}

/** The full text of src/gfx6/tables4.inc. */
export function genTables4() {
  const head = '; src/gfx6/tables4.inc -- GENERATED by tools/gen-tables.mjs. Do not edit by hand.\n' +
    '; Labels and data only. Every table is 256 bytes and must start on a page boundary: the including source\n' +
    '; puts this file at a page boundary (chunk 4-5) and the tables follow each other with no padding needed.\n';
  return [head, genLmaskp(), genRmaskp()].join('\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = genTables();
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(`${OUT}: ${Buffer.byteLength(text)} bytes`);
  const text4 = genTables4();
  writeFileSync(OUT4, text4);
  console.log(`${OUT4}: ${Buffer.byteLength(text4)} bytes`);
}
