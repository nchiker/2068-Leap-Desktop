"use strict";
// gen-icons.mjs -- the shell's icons (docs/SHELL.md 10.4): src/apps/icons.txt -> <dir>/icons.inc, G_BLIT shifted sets with
// copy 0 only (docs/GRAPHICS_SPIKE.md 15.2: ws = wb + 1 pairs a row, mask byte first).  Opaque: mask 0 over the icon's 32
// columns, the extra pair transparent (mask $FF, image 0).  A set drawn with copy 0 needs x AND 7 = 0.
// Paint's tool icons (docs/PAINT.md 7) are the same format 16 x 16 wide: src/apps/ticons.txt -> <dir>/ticons.inc (TICON_<name>).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const ICON_W = 32, ICON_H = 16;

export function parseIcons(text, file = 'icons.txt', W = ICON_W, H = ICON_H) {
  const icons = [];
  let cur = null;
  text.split('\n').forEach((line, i) => {
    const where = `${file}:${i + 1}`;
    if (!line.trim() || (line.trim().startsWith('#') && !/^[#.]+$/.test(line.trim()))) return;   // blank, or a comment (a '#' line that is not a bitmap row)
    const m = line.trim().match(/^icon\s+([A-Z0-9_]+)$/);
    if (m) { cur = { name: m[1], rows: [] }; icons.push(cur); return; }
    if (!cur) throw new Error(`${where}: a bitmap row before any "icon NAME"`);
    const row = line.trim();
    if (!/^[#.]+$/.test(row) || row.length !== W) throw new Error(`${where}: a row must be ${W} of '#' and '.'`);
    if (cur.rows.length >= H) throw new Error(`${where}: icon ${cur.name} has more than ${H} rows`);
    cur.rows.push(row);
  });
  for (const ic of icons) if (ic.rows.length !== H) throw new Error(`${file}: icon ${ic.name} has ${ic.rows.length} rows, not ${H}`);
  return icons;
}

/** The copy-0 set: per row, W / 8 (mask 0, image) pairs and one transparent pair. */
export function iconSet(rows, W = ICON_W) {
  const out = [];
  for (const row of rows) {
    for (let q = 0; q < W / 8; q++) {
      let b = 0;
      for (let j = 0; j < 8; j++) if (row[8 * q + j] === '#') b |= 0x80 >> j;
      out.push(0x00, b);
    }
    out.push(0xFF, 0x00);
  }
  return out;
}

function emit(icons, W, label, prefix) {
  const per = (W / 8 + 1) * 2;
  let text = `; ${label} -- GENERATED by tools/gen-icons.mjs. Do not edit by hand.\n`;
  for (const ic of icons) {
    const set = iconSet(ic.rows, W);
    text += `${prefix}_${ic.name}:\n`;
    for (let r = 0; r < ICON_H; r++) text += '    DB ' + set.slice(r * per, r * per + per).map((v) => `$${v.toString(16).toUpperCase().padStart(2, '0')}`).join(', ') + '\n';
  }
  return text;
}

export function genIcons(src, dir) {
  const icons = parseIcons(readFileSync(src, 'utf8'), src);
  writeFileSync(join(dir, 'icons.inc'), emit(icons, ICON_W, 'icons.inc', 'ICON'));
  return icons;
}

/** Paint's tool icons: 16 x 16, 3 pairs (6 bytes) a row, labelled TICON_<name> in the order of the file. */
export function genTicons(src, dir) {
  const icons = parseIcons(readFileSync(src, 'utf8'), src, 16, ICON_H);
  writeFileSync(join(dir, 'ticons.inc'), emit(icons, 16, 'ticons.inc', 'TICON'));
  return icons;
}
