"use strict";
// gen-icons.mjs -- the shell's icons (docs/SHELL.md 10.4): src/apps/icons.txt -> <dir>/icons.inc, G_BLIT shifted sets with
// copy 0 only (docs/GRAPHICS_SPIKE.md 15.2: ws = wb + 1 pairs a row, mask byte first).  Opaque: mask 0 over the icon's 32
// columns, the extra pair transparent (mask $FF, image 0).  A set drawn with copy 0 needs x AND 7 = 0.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const ICON_W = 32, ICON_H = 16;

export function parseIcons(text, file = 'icons.txt') {
  const icons = [];
  let cur = null;
  text.split('\n').forEach((line, i) => {
    const where = `${file}:${i + 1}`;
    if (!line.trim() || (line.trim().startsWith('#') && !/^[#.]+$/.test(line.trim()))) return;   // blank, or a comment (a '#' line that is not a bitmap row)
    const m = line.trim().match(/^icon\s+([A-Z0-9_]+)$/);
    if (m) { cur = { name: m[1], rows: [] }; icons.push(cur); return; }
    if (!cur) throw new Error(`${where}: a bitmap row before any "icon NAME"`);
    const row = line.trim();
    if (!/^[#.]+$/.test(row) || row.length !== ICON_W) throw new Error(`${where}: a row must be ${ICON_W} of '#' and '.'`);
    if (cur.rows.length >= ICON_H) throw new Error(`${where}: icon ${cur.name} has more than ${ICON_H} rows`);
    cur.rows.push(row);
  });
  for (const ic of icons) if (ic.rows.length !== ICON_H) throw new Error(`${file}: icon ${ic.name} has ${ic.rows.length} rows, not ${ICON_H}`);
  return icons;
}

/** The copy-0 set: per row, 4 (mask 0, image) pairs and one transparent pair. */
export function iconSet(rows) {
  const out = [];
  for (const row of rows) {
    for (let q = 0; q < ICON_W / 8; q++) {
      let b = 0;
      for (let j = 0; j < 8; j++) if (row[8 * q + j] === '#') b |= 0x80 >> j;
      out.push(0x00, b);
    }
    out.push(0xFF, 0x00);
  }
  return out;
}

export function genIcons(src, dir) {
  const icons = parseIcons(readFileSync(src, 'utf8'), src);
  let text = '; icons.inc -- GENERATED by tools/gen-icons.mjs from src/apps/icons.txt. Do not edit by hand.\n';
  for (const ic of icons) {
    const set = iconSet(ic.rows);
    text += `ICON_${ic.name}:\n`;
    for (let r = 0; r < ICON_H; r++) text += '    DB ' + set.slice(r * 10, r * 10 + 10).map((v) => `$${v.toString(16).toUpperCase().padStart(2, '0')}`).join(', ') + '\n';
  }
  writeFileSync(join(dir, 'icons.inc'), text);
  return icons;
}
