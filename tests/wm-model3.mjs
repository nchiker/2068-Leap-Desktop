// The pixels (18.3).  `g` is a Gfx6Model with the whole-screen clip.
export function drawBar(g, menus, lay) {
  g.setOp(OP_SET); g.fill(0, 0, 512, 8);
  if (menus && lay && lay.boxes) for (let i = 0; i < menus.length; i++) { g.setOp(OP_XOR); g.textp(lay.boxes[i].x + 8, 0, menus[i].title); }
}
/** The drop-down of menu i opened over whatever `g` holds, the title box inverted, the highlight on item h (-1 none): 18.3's steps 2-5 and the highlight. */
export function drawOpen(g, menus, lay, en, i, h) {
  const d = lay.drops[i], b = lay.boxes[i], m = menus[i];
  g.setOp(OP_CLR); g.fill(d.x, 8, d.w, d.h);
  g.setOp(OP_SET); g.frame(d.x, 8, d.w, d.h);
  g.fill(d.x + d.w, 10, 2, d.h - 1); g.fill(d.x + 2, 8 + d.h, d.w, 1);
  for (let k = 0; k < m.items.length; k++) {
    const it = m.items[k];
    g.setOp(OP_SET);
    if (it.flags & 2) { g.hline(d.x + 1, 13 + 10 * k, d.w - 2); continue; }
    g.textp(d.x + 8, 10 + 10 * k, it.text);
    if (!en[i][k]) { const t = tw(it.text); g.setOp(OP_CLR); for (const r of [11, 13, 15, 17]) g.fill(d.x + 8, r + 10 * k, t, 1); }
  }
  g.setOp(OP_XOR); g.fill(b.x, 0, b.w, 8);
  if (h >= 0) g.fill(d.x + 1, 9 + 10 * h, d.w - 2, 10);
}
export function cloneG(g) { const c = new Gfx6Model(); c.px.set(g.px); return c; }
/** The display bytes (y * 64 + byte column, as wm-lib.mjs's readDisp) as a Gfx6Model, and back. */
export function gFromDisp(disp) {
  const g = new Gfx6Model(), px = g.px;
  for (let y = 0; y < 192; y++) for (let bc = 0; bc < 64; bc++) { const v = disp[y * 64 + bc], i = y * 512 + bc * 8; for (let j = 0; j < 8; j++) px[i + j] = (v >> (7 - j)) & 1; }
  return g;
}
export function dispFromG(g) {
  const out = new Uint8Array(192 * 64), px = g.px;
  for (let y = 0; y < 192; y++) for (let bc = 0; bc < 64; bc++) { const i = y * 512 + bc * 8; out[y * 64 + bc] = (px[i] << 7) | (px[i + 1] << 6) | (px[i + 2] << 5) | (px[i + 3] << 4) | (px[i + 4] << 3) | (px[i + 5] << 2) | (px[i + 6] << 1) | px[i + 7]; }
  return out;
}

