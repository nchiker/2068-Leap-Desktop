  m.feed(ev(E.DOWN, 8, 3)); eq('x = 8 is Leap\'s box', m.trk && m.trk.i, 0); m.feed(ev(E.KEY, 3, 1, 1)); eq('BREAK closes with no choice', [m.trk, m.evlog.length], [null, 1]);
