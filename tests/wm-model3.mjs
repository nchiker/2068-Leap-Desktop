// The table (section 8) and its layout (18.2).
/** A menu spec: { id, title, items: [{ id, flags, text }] }; strings may be JS strings or code lists. */
export const menuSpec = (id, title, items) => ({ id, title: codes(title), items: items.map(([iid, flags, text]) => ({ id: iid, flags, text: codes(text) })) });
/** The bytes of a table at address `base`: count, a word per menu, then the records.  The counts are the specs' lengths (so a bad count can be built). */
export function encodeTable(menus, base) {
  const head = 1 + 2 * menus.length, recs = [], addrs = [];
  let off = head;
  for (const m of menus) {
    const b = [m.id, m.title.length, ...m.title, m.items.length];
    for (const it of m.items) b.push(it.id, it.flags, it.text.length, ...it.text);
    addrs.push(base + off); recs.push(b); off += b.length;
  }
  const out = [menus.length & 255];
  for (const a of addrs) out.push(a & 255, a >> 8);
  for (const b of recs) out.push(...b);
  return Uint8Array.from(out);
}
/** Read a table spec from memory (`rd(addr)` gives a byte), as the kernel would. */
export function readTable(rd, a) {
  const n = rd(a), menus = [];
  for (let i = 0; i < n; i++) {
    let p = rd(a + 1 + 2 * i) | (rd(a + 2 + 2 * i) << 8);
    const id = rd(p), tl = rd(p + 1), title = []; for (let j = 0; j < tl; j++) title.push(rd(p + 2 + j));
    let q = p + 2 + tl; const cnt = rd(q++), items = [];
    for (let k = 0; k < cnt; k++) { const iid = rd(q++), fl = rd(q++), l = rd(q++), text = []; for (let j = 0; j < l; j++) text.push(rd(q + j)); q += l; items.push({ id: iid, flags: fl, text }); }
    menus.push({ id, title, items });
  }
  return menus;
}
/**
 * 18.2.  Returns { ok, why, okStrict, okLenient, boxes: [{ x, w }], drops: [{ x, y: 8, w, h, n, save }] }.  `ok` is the strict reading (D1).
 * The save-under needs 4 + nc x (H + 1) bytes with nc = ((W + 2 + 7) >> 3) + 1 (strict) or (W + 2 + 7) >> 3 (lenient).
 */
export function layoutOf(menus) {
  const bad = (why) => ({ ok: false, okStrict: false, okLenient: false, why });
  if (!menus || menus.length < 1 || menus.length > 8) return bad('count');
  const boxes = [], drops = [];
  let x = 8, strict = true, lenient = true;
  for (const m of menus) {
    if (m.items.length < 1 || m.items.length > 15) return bad('items');
    const w = tw(m.title) + 16;
    boxes.push({ x, w }); x += w;
    const n = m.items.length, W = Math.max(...m.items.map((it) => tw(it.text))) + 24, H = 10 * n + 2;
    const ncS = ((W + 2 + 7) >> 3) + 1, ncL = (W + 2 + 7) >> 3;
    if (4 + ncS * (H + 1) > SAVE_MAX) strict = false;
    if (4 + ncL * (H + 1) > SAVE_MAX) lenient = false;
    drops.push({ x: Math.min(boxes[boxes.length - 1].x, 512 - (W + 2)), y: 8, w: W, h: H, n, save: 4 + ncS * (H + 1) });
  }
  if (x > 512) return bad('titles');
  return { ok: strict, okStrict: strict, okLenient: lenient, why: strict ? '' : 'save-under', boxes, drops };
}

