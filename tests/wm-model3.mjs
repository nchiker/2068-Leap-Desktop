// The input as the ISR turns it into events (OBJECTS_EVENTS 14.3 with WINDOWS 15.2), for the inputs the tests use.
export const KEYSPEC = {
  ENTER: { keys: [30], code: 13 }, a: { keys: [5], code: 97 }, x: { keys: [2], code: 120 }, q: { keys: [10], code: 113 },
  TAB: { keys: [0, 15], code: 14 }, BACKTAB: { keys: [0, 17], code: 15 }, ESC: { keys: [0, 18], code: 27 }, BREAK: { keys: [0, 35], code: 3 },
  MENU: { keys: [0, 21], code: 16 }, LEFT: { keys: [0, 19], code: 8 }, RIGHT: { keys: [0, 22], code: 9 }, UP: { keys: [0, 23], code: 11 }, DOWN: { keys: [0, 24], code: 10 },
};
export class Ptr {
  constructor(x, y) { this.x = x; this.y = y; this.btn = 0; this.px = x; this.py = y; }
  warp(x, y) { this.x = Math.min(Math.max(x, 0), 511); this.y = Math.min(Math.max(y, 0), 191); }
  /** One frame of input: { dx, dy (down positive), btn (the left button), key (a KEYSPEC name or null) }; the events in the ring's order. */
  step(inp) {
    const evs = [];
    this.px = this.x; this.py = this.y;
    if (inp.key) { const k = KEYSPEC[inp.key]; evs.push([E.KEY, k.code, k.keys.includes(0) ? 1 : 0, 0]); }
    const nx = Math.min(Math.max(this.x + (inp.dx || 0), 0), 511), ny = Math.min(Math.max(this.y + (inp.dy || 0), 0), 191), nb = inp.btn ? 1 : 0;
    const d3 = (nx >> 8) | (nb << 1);
    if (nx !== this.x || ny !== this.y) evs.push([E.MOVE, nx & 255, ny, d3]);
    if (nb !== this.btn) evs.push([nb ? E.DOWN : E.UP, nx & 255, ny, d3]);
    this.x = nx; this.y = ny; this.btn = nb;
    return evs;
  }
}

// ---------------------------------------------------------------------------------------------------------------------------
export class WmModel3 extends WmModel {
  constructor(deskAddr, barAddr) {
    super(deskAddr, barAddr);
    this.modal = 0;                  // the open Dialog (a node) or 0
    this.menus = null; this.lay = null; this.en = [];
    this.shown = { menus: null, lay: null };       // what the bar shows (updated when W_UPDATE paints the bar)
    this.trk = null;                 // tracking: { mode: 'ptr' | 'key', i, h }
    this.evlog = [];                 // the E_MENU records T_APPLOOP appends to T_EVLOG: [7, menu id, item id, 0]
    this.fault3 = 0;                 // --mutate N of tests/wm-w3.mjs: a planted fault
    this.stats3 = { opens: 0, switches: 0, choices: 0, noChoice: 0, escapes: 0, dropped: 0, handovers: 0, kbOpens: 0, kbIgnored: 0, wraps: 0, modalIgnored: 0, hi: 0, consumedBlock: 0 };
  }
  // ---- the menu bar routines (18.2, 18.5) ----------------------------------------------------------------------------------------
  damageBar() { for (let c = 0; c < COLS; c++) this.damageCell(c); }
  /** MB_SET.  `menus` null = MB_SET 0.  `reading` 'strict' | 'lenient' (D1).  Returns the carry. */
  setTable(menus, reading = 'strict') {
    if (menus === null) { this.menus = null; this.lay = null; this.en = []; this.damageBar(); return 0; }
    const lay = layoutOf(menus);
    if (!(reading === 'lenient' ? lay.okLenient : lay.okStrict)) return 1;
    this.menus = menus; this.lay = lay;
    this.en = menus.map((m) => m.items.map((it) => !(it.flags & 1) && !(it.flags & 2)));
    this.damageBar();
    return 0;
  }
  /** MB_ENABLE (A = menu, C = item, B = 0 / 1): a separator stays disabled; an index out of range does nothing. */
  mbEnable(a, c, b) {
    if (!this.menus || a >= this.menus.length || c >= this.menus[a].items.length) return;
    if ((this.menus[a].items[c].flags & 2) && this.fault3 !== 1) return;                      // fault 1: a separator can be enabled
    this.en[a][c] = !!b;
  }
  // ---- windows under it: 17.2's modal rule for a Dialog -------------------------------------------------------------------------------
  open(w) { const c = super.open(w); if (!c && w.kind === 'Dialog') this.modal = w; return c; }
  close(w) { if (w.slot !== 0 && this.modal === w) this.modal = 0; return super.close(w); }
  raise(w) { if (this.modal !== 0 && w !== this.modal) return 1; return super.raise(w); }
  drawNode(n, clip) {
    if (n.kind === 'Dialog') { this.stats.draws++; this.clip = clip.slice(); this.groupDraw(n, clip); this.clip = WHOLE.slice(); return; }
    super.drawNode(n, clip);
  }
  update() {
    const painted = super.update();
    if (painted.some((p) => p.o === 15)) this.shown = { menus: this.menus, lay: this.lay };
    return painted;
  }
  /** E_REDRAW once both queues are empty and a cell is dirty (the application is idle, no tracking). */
  idle() { if (!this.trk && this.anyDirty()) { this.update(); this.log = []; } }

  // ---- geometry helpers (18.4) -----------------------------------------------------------------------------------------------------
  boxAt(p) {
    if (!this.menus || p.y < 0 || p.y >= 8) return -1;
    for (let j = 0; j < this.lay.boxes.length; j++) if (p.x >= this.lay.boxes[j].x && p.x < this.lay.boxes[j].x + this.lay.boxes[j].w) return j;
    return -1;
  }
  /** The item whose hit area holds p in menu i, or -1: x + 1 <= px < x + W - 1 and 9 <= py < 9 + 10 n. */
  itemAt(i, p) {
    const d = this.lay.drops[i];
    if (p.x >= d.x + 1 && p.x < d.x + d.w - 1 && p.y >= 9 && p.y < 9 + 10 * d.n) return Math.floor((p.y - 9) / 10);
    return -1;
  }
  firstEnabled(i) { const e = this.en[i]; for (let k = 0; k < e.length; k++) if (e[k]) return k; return -1; }
  /** The next (dir 1) / previous (dir -1) enabled item of menu i from h, wrapping (D5); h when none is enabled. */
  stepEnabled(i, h, dir) {
    const e = this.en[i], n = e.length, start = h >= 0 ? h : (dir > 0 ? -1 : n);
    for (let s = 1; s <= n; s++) { const k = (((start + dir * s) % n) + n) % n; if (this.fault3 === 3 && ((dir > 0 && k <= start) || (dir < 0 && k >= start))) return h;   // fault 3: no wrap
      if (e[k]) { if ((dir > 0 && k <= start) || (dir < 0 && k >= start)) this.stats3.wraps++; return k; } }
    return h;
  }
  /** The item list of menu i, as the point of a screen position: where to put the pointer for item k (the middle of its hit area). */
  itemPoint(i, k) { const d = this.lay.drops[i]; return { x: d.x + (d.w >> 1), y: 9 + 10 * k + 5 }; }
  boxPoint(i) { const b = this.lay.boxes[i]; return { x: b.x + (b.w >> 1), y: 3 }; }

  // ---- events ----------------------------------------------------------------------------------------------------------------------
  /** The next event of the ring: to the tracking loop while one runs, else to K_DISPATCH. */
  feed(ev) { if (this.trk) this.trackEvent(ev); else this.dispatch(ev); }
  dispatch(ev) {
    const [type, d1, d2, d3] = ev, p = { x: d1 + 256 * (d3 & 1), y: d2 };
    if (type === E.KEY) { this.dispatchKey(d1); return; }
    if (type === E.DOWN) {
      if (this.modal !== 0) { this.stats3.modalIgnored++; return; }
      if (p.y < 8 && this.menus) { const j = this.boxAt(p); if (j >= 0) { this.trk = { mode: 'ptr', i: j, h: -1 }; this.stats3.opens++; } }
    } else if (this.modal !== 0 && (type === E.MOVE || type === E.UP)) this.stats3.modalIgnored++;
  }
  /** K_DISPATCH of an E_KEY: M_EVENT to K_FOCUS (or the desk) and up through the parents; the desk takes a MENU key (18.4); then the focus keys. */
  dispatchKey(code) {
    let v = this.focus || this.desk;
    while (v) {
      if (v.kind === 'TCtl') { this.rec(3, v); if (v.tag & 1) { if (code === K.MENU) this.stats3.consumedBlock++; return true; } }
      if (v === this.desk && code === K.MENU && this.modal === 0 && this.menus) { this.mbKey(); return true; }
      v = v.parent;
    }
    if ([K.TAB, K.DOWN, K.RIGHT].includes(code)) this.focusNext();
    else if ([K.BACKTAB, K.UP, K.LEFT].includes(code)) this.focusPrev();
    return false;
  }
  /** MB_KEY's start: the first menu with an enabled item, its first enabled item highlighted. */
  mbKey() {
    for (let i = 0; i < this.menus.length; i++) { const h = this.firstEnabled(i); if (h >= 0) { this.trk = { mode: 'key', i, h }; this.stats3.kbOpens++; return; } }
    this.stats3.kbIgnored++;
  }
  finish(choose) {
    const t = this.trk;
    if (choose && t.h >= 0) { this.evlog.push([E.MENU, this.menus[t.i].id, this.menus[t.i].items[t.h].id, 0]); this.stats3.choices++; }
    else this.stats3.noChoice++;
    this.trk = null;
  }
  trackEvent(ev) {
    const t = this.trk, [type, d1, d2, d3] = ev, p = { x: d1 + 256 * (d3 & 1), y: d2 };
    if (t.mode === 'ptr') {
      if (type === E.MOVE) this.ptrMove(p);
      else if (type === E.UP) this.finish(true);
      else if (type === E.KEY && (d1 === K.ESC || (d1 === K.BREAK && this.fault3 !== 5))) { this.stats3.escapes++; this.finish(false); }   // fault 5: BREAK does not close
      else this.stats3.dropped++;
      return;
    }
    if (type === E.KEY) {
      const n = this.menus.length;
      if (d1 === K.LEFT || d1 === K.RIGHT) { t.i = (t.i + (d1 === K.RIGHT ? 1 : n - 1)) % n; t.h = this.firstEnabled(t.i); this.stats3.switches++; }
      else if (d1 === K.UP || d1 === K.DOWN) t.h = this.stepEnabled(t.i, t.h, d1 === K.DOWN ? 1 : -1);
      else if (d1 === K.ENTER) this.finish(true);
      else if (d1 === K.ESC || d1 === K.BREAK || d1 === K.MENU) { if (d1 !== K.MENU) this.stats3.escapes++; this.finish(this.fault3 === 4 && d1 === K.BREAK); }   // fault 4: BREAK chooses
      else this.stats3.dropped++;
    } else if (type === E.DOWN) {
      const j = this.boxAt(p), k = j >= 0 ? -1 : this.itemAt(t.i, p);
      if (j >= 0) { if (j !== t.i) { t.i = j; t.h = -1; } t.mode = 'ptr'; this.stats3.handovers++; }
      else if (k >= 0) { t.h = this.en[t.i][k] ? k : -1; t.mode = 'ptr'; this.stats3.handovers++; }
      else if (this.fault3 === 7 && p.x >= this.lay.drops[t.i].x && p.x < this.lay.drops[t.i].x + this.lay.drops[t.i].w && p.y >= 8 && p.y < 8 + this.lay.drops[t.i].h) { t.h = -1; t.mode = 'ptr'; this.stats3.handovers++; }   // fault 7 (an experiment): the whole drop-down rectangle counts as inside
      else this.finish(false);
    } else this.stats3.dropped++;
  }
  ptrMove(p) {
    const t = this.trk, j = this.boxAt(p);
    if (j >= 0 && j !== t.i) { t.i = j; t.h = this.fault3 === 6 ? t.h : -1; this.stats3.switches++; return; }      // fault 6: h kept across a switch
    const k = this.itemAt(t.i, p);
    if (k >= 0) { t.h = (this.en[t.i][k] || this.fault3 === 2) ? k : -1; if (t.h >= 0) this.stats3.hi++; } else t.h = -1;   // fault 2: a disabled item is highlighted
  }
}

/**
 * The screen the contract fixes: `base` is the settled screen (a Gfx6Model; its bar rows are replaced by the model's bar), then the open menu's
 * pixels when the model is tracking.  `model.shown` is what the last W_UPDATE drew into the bar.
 */
export function expectedScreen(base, model) {
  const g = cloneG(base);
  drawBar(g, model.shown.menus, model.shown.lay);
  if (model.trk) drawOpen(g, model.menus, model.lay, model.en, model.trk.i, model.trk.h);
  return g;
}

