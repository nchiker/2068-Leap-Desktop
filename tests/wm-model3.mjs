export const E = { KEY: 1, MOVE: 2, DOWN: 3, UP: 4, REDRAW: 6, MENU: 7, CMD: 10 };
export const K = { BREAK: 3, LEFT: 8, RIGHT: 9, DOWN: 10, UP: 11, ENTER: 13, TAB: 14, BACKTAB: 15, MENU: 16, ESC: 27 };
export const SAVE_MAX = 2048;

// ---------------------------------------------------------------------------------------------------------------------------
// Strings and widths.
export const codes = (s) => (typeof s === 'string' ? Array.from(s, (c) => c.charCodeAt(0)) : Array.from(s));
/** G_TEXTW of a code list (lines split at 13, no menu string has one). */
export function tw(cs) {
  const W = fonts().prop6.W;
  let best = 0, cur = 0;
  for (const c of cs) { if (c === 13) { cur = 0; continue; } cur += W[c]; if (cur > best) best = cur; }
  return best;
}
/** A code string whose width is exactly `w` pixels (codes 33..126), or null when no such string exists (w = 1, 2). */
export function stringOfWidth(w) {
  const W = fonts().prop6.W;
  const best = new Array(w + 1).fill(null); best[0] = [];
  for (let t = 1; t <= w; t++) for (let c = 33; c <= 126; c++) if (W[c] > 0 && t >= W[c] && best[t - W[c]] && (!best[t] || best[t - W[c]].length + 1 < best[t].length)) best[t] = [...best[t - W[c]], c];
  return best[w];
}

