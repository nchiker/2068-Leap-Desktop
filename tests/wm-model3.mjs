// wm-model3.mjs -- reference model of slice W3 of the window manager: menus (docs/WINDOWS.md sections 8, 9, 17.3 and 18; the window manager it
// sits in: sections 2, 5, 6, 14).  Written from the contract only; the Z80 code (src/kernel/menu.asm, wm.asm, wm2.asm, kern4demo.asm) was never read.
//
//   node tests/wm-model3.mjs --self-test      hand-worked cases and invariants of the model itself
//
// What the model holds:
//   * the menu table (a spec: menus with ids, titles, items), `layoutOf` (18.2: title boxes, drop-down rectangles, the save-under rule), the enable
//     bits (`MB_SET`, `MB_ENABLE`), and `E_MENU`'s data;
//   * the pixels (18.3), as gfx6-model drawing: `drawBar`, `drawOpen` (drop-down, shadow, separators, dimmed items, inverted title box, highlight);
//     closing restores the screen exactly, so the screen with a menu open is a function of (the settled screen, the open state): `expectedScreen`;
//   * both tracking state machines (18.4): `WmModel3.feed(ev)` takes the next event the way T_APPLOOP's K_GETEV would: to the tracking loop while one
//     runs, else to K_DISPATCH (`dispatch`), where `desk_event` starts keyboard tracking on a MENU key that bubbled up unconsumed and
//     `mbar_event` starts pointer tracking on a press on a title box;
//   * the window manager under it, from tests/wm-model.mjs (W1: map, list, activation, focus) with 17.2's modal rule for a `Dialog`.
//
// Readings of the contract where its text leaves room (also listed in the report that came with this file):
//  D1. The save-under rule of 18.2, "4 + ((W + 2 + 7) >> 3 + 1) x (H + 1) > 2,048", is read as nc = ((W + 2 + 7) >> 3) + 1 byte columns (the worst
//      case of a W + 2 pixel wide rectangle at any x).  Section 2's example "96 pixels wide with 15 items" fits only with nc = (W + 2 + 7) >> 3 (the
//      "lenient" reading, 1,993 bytes); with the +1 it needs 2,146.  `layoutOf` reports both (`okStrict`, `okLenient`); the tests assert only
//      where they agree and report the band between them.
//  D2. A menu with a drop-down wider than the screen (W + 2 > 512) is outside the contract (the drop-down's x would be negative): the tests never
//      build one that MB_SET must accept.
//  D3. 18.3 step 4: only a text item is dimmed; a separator is its HLINE alone (no text, no dimming), though its enable bit is always 0.  The width
//      of a drop-down (18.2) takes every item's string, separators' included (the separators in T_MENUS have an empty string).
//  D4. 18.4: "p on another title box" means p's x in [box x, box x + box w) with p's y < 8 (the bar's rows; the box is 8 high); a move onto the open
//      menu's own title box falls through to "anywhere else": h = none.
//  D5. Keyboard UP / DOWN with h = none: DOWN goes to the first enabled item and UP to the last one (the walk starts before the first item / after
//      the last, and wraps).  18.4 says "the previous / next enabled item, wrapping" and nothing about none.  With an enabled item and h = it, a
//      menu whose only enabled item is h stays on it.
//  D6. Keyboard `E_DOWN` on the open menu's own title box: nothing changes (h too), tracking continues by pointer; on another title box h = none.
//  D7. LEFT / RIGHT with one menu only: the same menu "opens again" with h = its first enabled item (the pixels are the same as a fresh open).
//  D8. MENU with menus set, no modal, but no enabled item anywhere: consumed (nothing else could do anything with MENU), nothing opens.
//  D9. While tracking, no event other than the listed ones has an effect, and a pointer `E_DOWN` that closes a menu (keyboard tracking, "elsewhere")
//      is consumed: the press goes no further.
//  D10. MB_ENABLE with a B other than 0 or 1 is not exercised.  MB_ENABLE does not damage anything (the bar does not show enable bits).
//  D11. While a modal dialog is open, pointer events anywhere (the bar included) are ignored (17.3: consumed), and MENU does nothing.  Pointer events
//      outside tracking that reach a window are never generated by the tests except E_MOVE / E_UP, which change no state in W1-W3's model.
