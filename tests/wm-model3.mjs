  eq('the highlight on item 4 inverts (52..150, 49..58): (52, 49) was paper, is ink; row 59 is the frame; row 48 unchanged', [px(g1, 52, 49), px(gH, 52, 49), px(gH, 52, 48) === px(g1, 52, 48), px(gH, 100, 59) === px(g1, 100, 59)], [0, 1, true, true]);
  const gH2 = cloneG(gH); gH2.setOp(OP_XOR); gH2.fill(52, 49, 99, 10);
