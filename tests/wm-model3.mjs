  eq('separator row 33: x = 52..150 ink, 51 and 151 are the frame (ink), row 32 and 34 inside are paper', [px(g1, 52, 33), px(g1, 150, 33), px(g1, 100, 32), px(g1, 100, 34)], [1, 1, 0, 0]);
  eq('title box of File inverted: (51..85, 0..7) is paper where the bar was ink (corner (51, 0) paper), (50, 0) still ink', [px(g1, 51, 0), px(g1, 85, 7), px(g1, 50, 0), px(g1, 86, 0)], [0, 0, 1, 1]);
  // disabled "Quit" is item 3: text at (59, 40), rows 11 + 30 = 41, 43, 45, 47 cleared over x 59..80 (width 22)
  const gE = new Gfx6Model(); drawOpen(gE, MENUS, lay, [[true, true], [true, true, false, true, true], [true, true, true, true]], 1, -1);
  let inkOn = 0, inkOff = 0; for (let x = 59; x < 81; x++) for (const r of [41, 43, 45, 47]) { inkOn += px(gE, x, r); inkOff += px(g1, x, r); }
  eq('a disabled item has no ink on rows 41, 43, 45, 47 (11, 13, 15, 17 + 30), the enabled one has some', [inkOff, inkOn > 0], [0, true]);
  // highlight: XOR of (52, 9 + 10 k, 99, 10): item 4 "Print" rows 49..58
